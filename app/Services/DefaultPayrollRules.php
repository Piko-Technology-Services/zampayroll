    /**
     * Create (or refresh) the default rules for one company.
     */
    public static function seedFor(int $companyId): int
    {
        $count = 0;

        Tenancy::runAs($companyId, function () use ($companyId, &$count) {
            foreach (static::definitions() as $rule) {
                PayrollRule::updateOrCreate(
                    ['company_id' => $companyId, 'code' => $rule['code']],
                    $rule
                );
                $count++;
            }
        });

        return $count;
    }

    /**
     * Seed only when the company has no rules yet (safe to call repeatedly).
     */
    public static function ensureFor(int $companyId): void
    {
        $has = PayrollRule::withoutGlobalScope('company')->where('company_id', $companyId)->exists();

        if (! $has) {
            static::seedFor($companyId);
        }
    }
